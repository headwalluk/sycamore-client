// Command emojigen writes the TUI's emoji shortcode table from GitHub's
// gemoji list, as bundled in goldmark-emoji's _tools/github.json. Usage:
// emojigen <github.json> <output.go>. Run it through `go generate ./tui`.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
)

// gemojiList is the shape of goldmark-emoji's github.json.
type gemojiList struct {
	Data []struct {
		ShortNames []string
		Unicode    []string
	} `json:"data"`
}

// replacementCodepoint marks GitHub's image-only codes (:octocat:), which
// have no Unicode form.
const replacementCodepoint = 0xFFFD

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: emojigen <github.json> <output.go>")
		os.Exit(2)
	}
	if err := generate(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintf(os.Stderr, "emojigen: %v\n", err)
		os.Exit(1)
	}
}

// generate reads the gemoji list and writes the sorted Go table.
func generate(inputPath, outputPath string) error {
	source, err := os.ReadFile(inputPath)
	if err != nil {
		return err
	}
	var list gemojiList
	if err := json.Unmarshal(source, &list); err != nil {
		return fmt.Errorf("%s: %w", inputPath, err)
	}

	glyphs := map[string]string{}
	var glyphErr error
	for _, emoji := range list.Data {
		glyph, err := glyphOf(emoji.Unicode)
		if err != nil {
			glyphErr = fmt.Errorf("%v: %w", emoji.ShortNames, err)
			break
		}
		for _, code := range emoji.ShortNames {
			if glyph != "" {
				glyphs[code] = glyph
			}
		}
	}
	if glyphErr != nil {
		return glyphErr
	}
	codes := make([]string, 0, len(glyphs))
	for code := range glyphs {
		codes = append(codes, code)
	}
	sort.Strings(codes)

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by tui/internal/tools/emojigen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "package main\n\n")
	fmt.Fprintf(&out, "// emojiTable is GitHub's gemoji shortcodes, sorted by code.\n")
	fmt.Fprintf(&out, "var emojiTable = []emojiCode{\n")
	for _, code := range codes {
		fmt.Fprintf(&out, "\t{%s, %s},\n", strconv.Quote(code), strconv.Quote(glyphs[code]))
	}
	fmt.Fprintf(&out, "}\n")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return fmt.Errorf("formatting the table: %w", err)
	}
	return os.WriteFile(outputPath, formatted, 0o644)
}

// glyphOf builds an emoji from its decimal codepoints; "" for an image-only one.
func glyphOf(codepoints []string) (string, error) {
	var runes []rune
	var parseErr error
	for _, text := range codepoints {
		codepoint, err := strconv.ParseInt(text, 10, 32)
		if err != nil {
			parseErr = fmt.Errorf("codepoint %q: %w", text, err)
			break
		}
		runes = append(runes, rune(codepoint))
	}
	glyph := ""
	if parseErr == nil && !(len(runes) == 1 && runes[0] == replacementCodepoint) {
		glyph = string(runes)
	}
	return glyph, parseErr
}
